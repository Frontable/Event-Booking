CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT                   NOT NULL REFERENCES rooms (id),
    title       VARCHAR(200)             NOT NULL,
    description VARCHAR(2000),
    starts_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity    INTEGER                  NOT NULL CHECK (capacity > 0),
    price       NUMERIC(10, 2)           NOT NULL CHECK (price >= 0),
    status      VARCHAR(20)              NOT NULL CHECK (status IN ('PUBLISHED', 'CANCELLED')),
    CONSTRAINT events_time_order CHECK (ends_at > starts_at),
    CONSTRAINT events_no_room_overlap EXCLUDE USING gist (
        room_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status = 'PUBLISHED')
);

CREATE INDEX ix_events_room ON events (room_id);
CREATE INDEX ix_events_starts_at ON events (starts_at);
